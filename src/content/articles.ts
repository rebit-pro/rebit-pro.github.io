export function findArticle(slug: string): Article | undefined {
  return articles.find((item) => item.slug === slug)
}

/**
 * Возвращает JSON-LD (Article + FAQPage) для статьи в виде готовых тегов <script>.
 * Используется при пререндере для вставки структурированных данных в <head>.
 */
export function articleJsonLd(article: Article, domain: string, organization: string): string {
  const canonical = `${domain}/blog/${article.slug}/`

  const articleSchema = {
    '@context': 'https://schema.org',
    '@type': 'Article',
    headline: article.title,
    description: article.metaDescription,
    inLanguage: 'ru-RU',
    keywords: article.keywords.join(', '),
    dateModified: article.updated,
    mainEntityOfPage: { '@type': 'WebPage', '@id': canonical },
    author: { '@type': 'Organization', name: organization, url: `${domain}/` },
    publisher: {
      '@type': 'Organization',
      name: organization,
      logo: { '@type': 'ImageObject', url: `${domain}/logo-rebit-studio.svg` },
    },
  }

  const faqSchema = {
    '@context': 'https://schema.org',
    '@type': 'FAQPage',
    mainEntity: article.faq.map((item) => ({
      '@type': 'Question',
      name: item.question,
      acceptedAnswer: { '@type': 'Answer', text: item.answer },
    })),
  }

  return [articleSchema, faqSchema]
    .map((schema) => `<script type="application/ld+json">${JSON.stringify(schema)}</script>`)
    .join('')
}
